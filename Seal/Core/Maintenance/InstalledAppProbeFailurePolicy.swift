import Foundation

/// 「设备核验失败了 —— 这是**哪种**失败、该不该打断用户」的**纯判据**。
///
/// ## 为什么需要它（2026-09-22 用户报障）
///
/// 用户：「把你发现的问题也修复，因为**有时候刷新还是出现弹窗让去检测 VPN**。」
///
/// 真机日志（构建 199）显示这条路径一点都不罕见：`SEAL-RECONCILE-003`
///（阳性对照未通过 ⇒ 整轮不删）在 **90 分钟里出现 10 次**，每次都是同一个 Bundle ID，
/// 而**同一条通道 3 秒后就恢复正常**（10:21:30 中止 → 10:21:33 完成「探测 2 条，删除 0 条」）
/// ⇒ 那不是「通道不可信」，是**通道还没起来**。
///
/// 而当时只要 `userInitiated`（下拉刷新）就会弹一个模态窗，按钮文案经 `settingsRoute`
/// 被路由到 **LocalDevVPN 设置页**（它对 `SEAL-INSTALL-` 前缀一律如此）
/// ⇒ 用户每下拉一次刷新就被推进 VPN 页面，**而实际上什么都没坏**
///（列表已从本地库刷新过，只是「设备端核销」这一轮跳过了）。
///
/// ## 两种失败必须分开（这是本判据的全部内容）
///
/// 底层是一条同步阻塞 FFI（`Minimuxer.isAppInstalled`，上限 `BlockingCall.queryTimeoutSeconds`）。
/// 真机上它有两种**形态完全不同**的失败，`DeviceProfileCleaner` 早就按耗时区分过
///（日志里的 `查询失败(0.0s)` 与 `查询失败(15.0s)`）：
///
/// - **快速失败**（≈0 秒就抛）：RSD 会话**还没建好**，FFI 立刻返回错误
///   ⇒ 等一会儿再问多半就好了 ⇒ 属于第③类「条件不满足 ⇒ 跳过」，**不该报给用户**；
/// - **慢速失败**（撞满超时）：会话**已经死了**（隧道断了 / VPN 关了）
///   ⇒ 这时「去查 LocalDevVPN」才是**有用的动作**，值得打断用户。
///
/// ⇒ **只有 `.sessionDead` 才弹窗。** 这样无论通道恢复用 1 秒还是 10 秒，假警报都不会再出现。
/// ⚠️ 「把重试窗口加长」做不到这件事 —— 真机实测重试窗口 ~2.2 秒、而通道恢复要 ~3 秒，
/// 加长只是把假警报的**概率**变小，判据本身仍然是「问一次没答对就当成通道不可信」✗。
///
/// 做成纯函数是因为它的错法同样是「不崩、不编译失败，只在真机上表现为弹窗变多或刷新变慢」，
/// 只能靠单测 + 守卫断言钉住。
enum InstalledAppProbeFailurePolicy {
    /// 一次核验失败的形态。
    enum Kind: Equatable {
        /// **快速失败**（≈0 秒）：通道还没起来 ⇒ 等一会儿多半就好。
        case transient
        /// **慢速失败**（撞满超时）：会话已经死了 ⇒ 再问一次也只是再等一个超时。
        case sessionDead
    }

    /// 「快速失败」的耗时上界（秒）。**达到或超过**它，说明这次是撞满超时。
    ///
    /// 取 3 秒：真机实测快速失败是 `0.0s` 量级、超时失败是 15 秒量级，
    /// 两者相差一个数量级，中间取一个远离两侧的值即可。
    /// 判据用 `>=`（恰好落在上界上算「慢」）—— 与重试判据的 `<` **严格互补**。
    static let fastFailureUpperBound: TimeInterval = 3.0

    /// 按耗时给这次失败定性。
    static func kind(elapsed: TimeInterval) -> Kind {
        return elapsed >= fastFailureUpperBound ? .sessionDead : .transient
    }

    /// 这次失败值不值得**打断用户**（模态弹窗，且按钮会被路由到 LocalDevVPN 设置页）。
    ///
    /// 只有 `.sessionDead` 值得：那时「去查 VPN」真的能解决问题。
    /// `.transient` 必须静默 —— 本轮**什么都没改**（记录一条都没删），
    /// 按本仓的日志纪律属于第③类「条件不满足 ⇒ 跳过」，不是该报给用户的失败。
    static func deservesUserAttention(_ kind: Kind) -> Bool {
        return kind == .sessionDead
    }
}
